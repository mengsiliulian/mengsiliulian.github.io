// 从 327 条"例:"usage 中, 自动标记"纯凑数/专名描述性"可疑条目(不含真正有固定搭配/动词用法的)
// 只输出候选清单供人工确认, 不改数据
const db = require('../source/meme/memes.json');
const hard = db.entries.filter(e => e.usage && /^例\s*[:：]/.test(e.usage.trim()));

// 判定为"有用用法"的正向特征(有固定搭配/动词/口头禅):
//  - 含明显动词搭配词: 被xx/掉/上车/下头/上头/发/收/圈/抢/翻/打/玩/看/反/卷
//  - 含固定句式词: 一生平安/名场面/天花板/秒空/保熟...
// 但更稳妥: 用负向特征标记"纯描述/强行夸"的,
// 有这些模式多半是废话: 「XX[的][就是/都/真|太/很]」+ 主观评价(潮/经典/好看/强/燃/治愈/震撼/精致/上头/丧/美/帅)
// 或者 「例：XX[主语部分], [评论]」 - 这个难自动判

// 抽取 u 去掉 '例:' 后的正文
const parse = e => (e.usage||'').replace(/^例\s*[:：]\s*/,'');

// 可疑"凑数夸"词
const praiseKw = ['太经典','真经典','很经典','太燃','美到','太治愈','太强','太帅','太潮','太好看','太好看了','太震撼','震撼到','美得','帅到','太顶','天花板','吹爆','太可爱','太魔性','太洗脑','太有喜感','太感人','看哭','太招人喜欢','太让人','真是经典','经典中的经典','神作','白月光','好评','口碑','太惊艳','太能打','太有排面','无出其右','无人能及','意难平','太矫情','太上头','太好看'];
// 描述型(主语+评论, 无固定搭配)特征: 句子以专名开头并表"是什么/怎么样", 含判断词 是/的/都/就
function isFiller(e){
  const t = parse(e);
  // 明确有用的固定搭配模式 -> 保留
  if(/被[^，。]{1,6}|掉[^，。]{1,4}|圈粉|粉转黑|黑转粉|一步到位|秒空|买单|上头|下头|入坑|翻车|上岸|开盒|背刺|被整|慌了|破防|社死|卡(死|机)|断网|蓝屏|死机|发好人卡|领盒饭|摸鱼|上班|加班|内卷|躺平|暴富|A\b/.test(t)) return false;
  // 纯"XX[的]..."起头 + 评价词 -> 可疑
  // 例子: 宫崎骏的动画每次重映我都会去看(无固定搭配) / 米老鼠那张圆脸全世界都认得
  if(/^[^，。！？]{2,12}[的了是就]/.test(t) && praiseKw.some(k=>t.includes(k))) return true;
  // "XX是..." 且短评
  if(/^[^，。！？]{2,14}(是|就是)[^，。！？]{2,14}(经典|开端|巅峰|童年|图腾|代名词|起点|必杀|标配|招牌|名场面|代表作)/.test(t)) return true;
  return false;
}
const cand = hard.filter(isFiller);
console.log('候选"凑数"条目:', cand.length, ' / 共', hard.length);
cand.forEach(e=>console.log(' * ['+e.type+'] '+e.name+' :: '+(e.usage||'')));
